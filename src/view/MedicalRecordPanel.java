    public void setMedicalRecords(java.util.List<model.MedicalRecord> records) {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        for (model.MedicalRecord r : records) {
            String reportText = r.getPrescription() + " | " + r.getNotes();
            model.addRow(new Object[]{
                r.getRecordDate(),
                r.getDoctorName(),
                r.getDepartmentName(),
                r.getDiagnosis(),
                reportText
            });
        }
    }
