package model;

/**
 * UserModel — a plain Java class (POJO) that maps to the 'users' table.
 *
 * Fields match the database columns:
 *   user_id     INT AUTO_INCREMENT (primary key)
 *   username    VARCHAR
 *   password    VARCHAR
 *   role        ENUM ("patient", "doctor", "receptionist", "admin")
 *
 * Architecture Rule: This class contains ONLY data fields + constructor + getters + setters.
 * No SQL, no UI code allowed here.
 *
 * @author Group 3 C39A
 */
public class UserModel {

    // ==================== Fields ====================

    private int    userId;    // auto-incremented primary key from users table
    private String username;  // login username (e.g., phone number or chosen name)
    private String password;  // login password
    private String role;      // "patient", "doctor", "receptionist", or "admin"

    // ==================== Constructors ====================

    /**
     * Default (no-argument) constructor.
     * Use when creating an empty object and setting fields one by one with setters.
     */
    public UserModel() {
        // empty — fields will be set using setters
    }

    /**
     * Full constructor — use when you already have all values (e.g., reading from DB).
     *
     * @param userId   the user's auto-generated primary key from the database
     * @param username the user's login username
     * @param password the user's login password
     * @param role     the user's role ("patient", "doctor", "receptionist", "admin")
     */
    public UserModel(int userId, String username, String password, String role) {
        this.userId   = userId;
        this.username = username;
        this.password = password;
        this.role     = role;
    }

    /**
     * Constructor WITHOUT userId — use when registering a NEW user.
     * The userId will be auto-generated by MySQL, so we don't pass it here.
     *
     * @param username the user's login username
     * @param password the user's login password
     * @param role     the user's role ("patient", "doctor", "receptionist", "admin")
     */
    public UserModel(String username, String password, String role) {
        this.username = username;
        this.password = password;
        this.role     = role;
    }

    // ==================== Getters ====================
    // Getters allow other classes to READ the private fields

    /**
     * @return the user's ID (auto-generated primary key)
     */
    public int getUserId() {
        return userId;
    }

    /**
     * @return the user's login username
     */
    public String getUsername() {
        return username;
    }

    /**
     * @return the user's login password
     */
    public String getPassword() {
        return password;
    }

    /**
     * @return the user's role ("patient", "doctor", "receptionist", "admin")
     */
    public String getRole() {
        return role;
    }

    // ==================== Setters ====================
    // Setters allow other classes to WRITE/UPDATE the private fields

    /**
     * @param userId the user ID to set
     */
    public void setUserId(int userId) {
        this.userId = userId;
    }

    /**
     * @param username the login username to set
     */
    public void setUsername(String username) {
        this.username = username;
    }

    /**
     * @param password the login password to set
     */
    public void setPassword(String password) {
        this.password = password;
    }

    /**
     * @param role the user role to set ("patient", "doctor", "receptionist", "admin")
     */
    public void setRole(String role) {
        this.role = role;
    }

    /**
     * Returns a human-readable string representation of this UserModel.
     * Useful for debugging (e.g., System.out.println(user)).
     * Note: password is hidden for security.
     */
    @Override
    public String toString() {
        return "UserModel{" +
               "userId=" + userId +
               ", username='" + username + '\'' +
               ", password='[HIDDEN]'" +
               ", role='" + role + '\'' +
               '}';
    }
}
